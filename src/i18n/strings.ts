const dictionaries: Record<Lang, Record<MessageKey, string>> = { en, ja };

export type MessageParams = Record<string, string | number>;

// Look up a message and fill in {placeholders}
export const translate = (lang: Lang, key: MessageKey, params?: MessageParams): string =>
  (dictionaries[lang][key] ?? en[key]).replace(/\{(\w+)\}/g, (match, name: string) =>
    params && name in params ? String(params[name]) : match
  );
